"""Fetch a 210 m x 240 m window of a real NASA HiRISE terrain model of Jezero crater.

Source: HiRISE DTM DTEEC_023524_1985_023379_1985_U01 (1 m/pixel, PDS3, 32-bit float),
University of Arizona / NASA MRO HiRISE team. Only the needed rows are downloaded with
HTTP range requests, so the 700 MB product is never fetched in full.

Writes:
  public/data/raw/jezero-dtm/window.json   raw 1 m heights (metres, areoid), with label facts
  data/jezero-terrain.js                   2 m game grid, heights relative to the outpost

Run:  python3 scripts/fetch-jezero-dtm.py
"""
from __future__ import annotations
import hashlib, json, struct, subprocess
from pathlib import Path

URL = ("https://www.uahirise.org/PDS/DTM/ESP/ORB_023500_023599/ESP_023524_1985_ESP_023379_1985/"
       "DTEEC_023524_1985_023379_1985_U01.IMG")
RECORD_BYTES, SAMPLES = 32940, 8235          # from the attached PDS label
FIRST_LINE, FIRST_SAMPLE = 3960, 3480        # chosen: gentle 15 m rise to the north, no gaps
LINES, COLS = 240, 210                        # game bounds: x -100..110, z -198..40 (1 m = 1 game unit)
ROOT = Path(__file__).resolve().parent.parent

def fetch() -> list[list[float]]:
    start = RECORD_BYTES * (1 + FIRST_LINE)   # image begins at record 2
    end = start + RECORD_BYTES * LINES - 1
    raw = subprocess.run(["curl", "-sSf", "-m", "300", "-r", f"{start}-{end}", URL], capture_output=True, check=True).stdout
    if len(raw) != RECORD_BYTES * LINES:
        raise SystemExit(f"short read: {len(raw)} bytes")
    rows = []
    for line in range(LINES):
        values = struct.unpack_from(f"<{COLS}f", raw, line * RECORD_BYTES + FIRST_SAMPLE * 4)
        if any(v < -1e5 for v in values):
            raise SystemExit("window contains missing data")
        rows.append([round(v, 2) for v in values])
    return rows

def smooth(rows):  # 3x3 box filter removes 1 m stereo noise the rover would feel as jitter
    out = []
    for r in range(LINES):
        out.append([sum(rows[rr][cc] for rr in range(max(0, r-1), min(LINES, r+2)) for cc in range(max(0, c-1), min(COLS, c+2)))
                    / (len(range(max(0, r-1), min(LINES, r+2))) * len(range(max(0, c-1), min(COLS, c+2)))) for c in range(COLS)])
    return out

def main() -> None:
    rows = fetch()
    raw_dir = ROOT / "public/data/raw/jezero-dtm"; raw_dir.mkdir(parents=True, exist_ok=True)
    record = {"product": "DTEEC_023524_1985_023379_1985_U01", "sourceUrl": URL,
              "label": {"MAP_SCALE_m_per_px": 1.0096633268711, "MAP_PROJECTION_TYPE": "EQUIRECTANGULAR",
                        "CENTER_LATITUDE": 15.0, "CENTER_LONGITUDE": 77.53, "MINIMUM_LATITUDE": 18.159317160581,
                        "MAXIMUM_LATITUDE": 18.521550219233, "WESTERNMOST_LONGITUDE": 77.45290261,
                        "EASTERNMOST_LONGITUDE": 77.59817341, "units": "metres above the Mars areoid"},
              "window": {"firstLine": FIRST_LINE, "firstSample": FIRST_SAMPLE, "lines": LINES, "samples": COLS},
              "heights": rows}
    text = json.dumps(record, separators=(",", ":"))
    (raw_dir / "window.json").write_text(text)
    sm = smooth(rows)
    # Game grid every 2 m: x = -100 + 2*i, z = -198 + 2*j. Outpost (HOME x=10, z=10) is height 0.
    home = sm[10 + 198][10 + 100]
    grid = [[round((sm[min(LINES-1, 2*j)][min(COLS-1, 2*i)] - home) * 10) for i in range(COLS // 2 + 1)] for j in range(LINES // 2 + 1)]
    js = ("// Generated by scripts/fetch-jezero-dtm.py. Do not edit by hand.\n"
          "// Real NASA HiRISE terrain (Jezero crater, 1 m/pixel), smoothed and sampled every 2 m.\n"
          f"// Values are decimetres relative to the outpost. Source sha256 {hashlib.sha256(text.encode()).hexdigest()}.\n"
          "export const JEZERO={product:'DTEEC_023524_1985_023379_1985_U01',step:2,minX:-100,minZ:-198,"
          f"cols:{len(grid[0])},rows:{len(grid)},homeAreoidMetres:{home:.2f},\n data:{json.dumps(grid, separators=(',', ':'))}}};\n")
    (ROOT / "data/jezero-terrain.js").write_text(js)
    print("window", FIRST_LINE, FIRST_SAMPLE, "relief", round(max(map(max, rows)) - min(map(min, rows)), 2), "m")

if __name__ == "__main__":
    main()
