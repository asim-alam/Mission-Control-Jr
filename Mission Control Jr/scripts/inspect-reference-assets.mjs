const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = process.argv[2] || 'C:/Users/BMCT LTD/Downloads';
const destination = path.join(root, 'assets/models');
await fs.mkdir(destination, { recursive: true });
const sources = [
  ['mars_-_olympus_mons.glb', 'reference-olympus-mons'],
  ['perseverance_-_nasa_mars_landing_2021.glb', 'reference-perseverance'],
  ['mars_rover.glb', 'reference-mars-rover'],
  ['mars.glb', 'reference-mars-globe'],
];
const component = { 5120: [Int8Array, 1], 5121: [Uint8Array, 1], 5122: [Int16Array, 2], 5123: [Uint16Array, 2], 5125: [Uint32Array, 4], 5126: [Float32Array, 4] };
const sizes = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4, MAT4: 16 };
const semantics = { POSITION: 'position', NORMAL: 'normal', TANGENT: 'tangent', TEXCOORD_0: 'uv', TEXCOORD_1: 'uv1', TEXCOORD_2: 'uv2', TEXCOORD_3: 'uv3', COLOR_0: 'color' };
const report = [];

function readGLB(bytes) {
  if (bytes.readUInt32LE(0) !== 0x46546c67 || bytes.readUInt32LE(4) !== 2) throw new Error('Not a GLB 2.0 file');
  let json, binary;
  for (let offset = 12; offset < bytes.length;) {
    const length = bytes.readUInt32LE(offset), type = bytes.readUInt32LE(offset + 4);
    const chunk = bytes.subarray(offset + 8, offset + 8 + length);
    if (type === 0x4e4f534a) json = JSON.parse(chunk.toString());
    if (type === 0x004e4942) binary = chunk;
    offset += 8 + length;
  }
  return { json, binary };
}
function accessor(json, binary, index) {
  const a = json.accessors[index], view = json.bufferViews[a.bufferView];
  if (a.sparse || !view) throw new Error('Sparse/accessor-only geometry requires another conversion pipeline');
  const [Type, width] = component[a.componentType], count = sizes[a.type];
  const stride = view.byteStride || width * count, start = (view.byteOffset || 0) + (a.byteOffset || 0);
  const output = new Float32Array(a.count * count);
  for (let i = 0; i < a.count; i++) {
    for (let k = 0; k < count; k++) {
      const offset = start + i * stride + k * width;
      let value;
      if (Type === Float32Array) value = binary.readFloatLE(offset);
      else if (Type === Uint32Array) value = binary.readUInt32LE(offset);
      else if (Type === Uint16Array) value = binary.readUInt16LE(offset);
      else if (Type === Int16Array) value = binary.readInt16LE(offset);
      else if (Type === Int8Array) value = binary.readInt8(offset);
      else value = binary.readUInt8(offset);
      if (a.normalized) value = a.componentType === 5120 ? Math.max(-1, value / 127) : a.componentType === 5122 ? Math.max(-1, value / 32767) : value / (2 ** (8 * width) - 1);
      output[i * count + k] = value;
    }
  }
  return new THREE.BufferAttribute(output, count);
}
function collectGeometry(json, binary, removePresentationFloor = false) {
  const groups = new Map(), bounds = new THREE.Box3(), traversal = [];
  const visit = (id, parent) => {
    const node = json.nodes[id], local = new THREE.Matrix4();
    if (node.matrix) local.fromArray(node.matrix);
    else local.compose(new THREE.Vector3().fromArray(node.translation || [0, 0, 0]), new THREE.Quaternion().fromArray(node.rotation || [0, 0, 0, 1]), new THREE.Vector3().fromArray(node.scale || [1, 1, 1]));
    const world = parent.clone().multiply(local);
    if (node.mesh !== undefined) {
      for (const primitive of json.meshes[node.mesh].primitives) {
        if ((primitive.mode ?? 4) !== 4 || primitive.targets || node.skin !== undefined) throw new Error('Only static triangles are supported');
        const geometry = new THREE.BufferGeometry();
        const material = json.materials?.[primitive.material];
        if (removePresentationFloor && /sketchfab_floor/i.test(material?.name || '')) continue;
        const requiredUVs = new Set();
        const inspectTextures = value => {
          if (!value || typeof value !== 'object') return;
          if ('index' in value) requiredUVs.add(value.texCoord || 0);
          for (const item of Object.values(value)) inspectTextures(item);
        };
        inspectTextures(material);
        for (const [semantic, index] of Object.entries(primitive.attributes)) {
          // Tangents are regenerated by Three.js normal-map derivatives after static batching.
          if (semantic === 'TANGENT') continue;
          if (semantic.startsWith('TEXCOORD_') && !requiredUVs.has(Number(semantic.slice(9)))) continue;
          if (!semantics[semantic]) throw new Error(`Unsupported static attribute ${semantic}`);
          geometry.setAttribute(semantics[semantic], accessor(json, binary, index));
        }
        if (primitive.indices !== undefined) geometry.setIndex(new THREE.BufferAttribute(Uint32Array.from(accessor(json, binary, primitive.indices).array), 1));
        else geometry.setIndex(Array.from({ length: geometry.attributes.position.count }, (_, i) => i));
        geometry.applyMatrix4(world);
        if (world.determinant() < 0) {
          const a = geometry.index.array;
          for (let i = 0; i < a.length; i += 3) [a[i + 1], a[i + 2]] = [a[i + 2], a[i + 1]];
        }
        geometry.computeBoundingBox(); bounds.union(geometry.boundingBox);
        const key = `${primitive.material ?? -1}:${Object.keys(geometry.attributes).sort().join(',')}`;
        if (!groups.has(key)) groups.set(key, { material: primitive.material, geometries: [] });
        groups.get(key).geometries.push(geometry);
        traversal.push({ name: node.name, triangles: geometry.index.count / 3 });
      }
    }
    for (const child of node.children || []) visit(child, world);
  };
  for (const node of json.scenes[json.scene || 0].nodes) visit(node, new THREE.Matrix4());
  return { groups, bounds, traversal };
}

for (const [filename, outputName] of sources) {
  const original = await fs.readFile(path.join(sourceDirectory, filename));
  const { json, binary } = readGLB(original);
  const originalExtensionsUsed = [...(json.extensionsUsed || [])];
  const originalExtensionsRequired = [...(json.extensionsRequired || [])];
  // The supplied globe uses a legacy diffuse/specular material unsupported by
  // current GLTFLoader. This particular matte material has zero specular and no
  // specular texture, so a diffuse-preserving core PBR approximation is suitable.
  const legacyMaterial = 'KHR_materials_pbrSpecularGlossiness';
  if (filename === 'mars.glb' && json.extensionsRequired?.includes(legacyMaterial)) {
    for (const material of json.materials || []) {
      const legacy = material.extensions?.[legacyMaterial];
      if (!legacy) continue;
      if (legacy.specularGlossinessTexture || legacy.specularFactor?.some(value => value !== 0)) throw new Error('Unexpected non-matte globe material needs manual conversion');
      material.pbrMetallicRoughness = {
        baseColorFactor: legacy.diffuseFactor || [1, 1, 1, 1],
        ...(legacy.diffuseTexture ? { baseColorTexture: legacy.diffuseTexture } : {}),
        metallicFactor: 0,
        roughnessFactor: 1 - (legacy.glossinessFactor ?? 1),
      };
      delete material.extensions[legacyMaterial];
      if (!Object.keys(material.extensions).length) delete material.extensions;
    }
    json.extensionsUsed = json.extensionsUsed.filter(extension => extension !== legacyMaterial);
    json.extensionsRequired = json.extensionsRequired.filter(extension => extension !== legacyMaterial);
  }
  const external = [...(json.buffers || []), ...(json.images || [])].flatMap(item => item.uri ? [item.uri] : []);
  if (external.length || json.animations?.length || json.extensionsRequired?.length) throw new Error(`${filename}: external resources/animation/required extensions need manual review`);
  const { groups, bounds, traversal } = collectGeometry(json, binary, true);
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'mission-control-reference-'));
  const imageInfo = [];
  const jobs = [];
  for (let i = 0; i < (json.images || []).length; i++) {
    const image = json.images[i], view = json.bufferViews[image.bufferView];
    const input = path.join(temporary, `source-${i}`), output = path.join(temporary, `output-${i}`);
    await fs.writeFile(input, binary.subarray(view.byteOffset || 0, (view.byteOffset || 0) + view.byteLength));
    jobs.push({ input, output, mimeType: image.mimeType, maxSize: 1024 });
  }
  await fs.writeFile(path.join(temporary, 'jobs.json'), JSON.stringify(jobs));
  const python = spawnSync('python', ['-c', `import json,sys\nfrom PIL import Image\njobs=json.load(open(sys.argv[1]))\nfor j in jobs:\n im=Image.open(j['input']); j['sourceSize']=list(im.size); im.thumbnail((j['maxSize'],j['maxSize']),Image.Resampling.LANCZOS)\n if j['mimeType']=='image/jpeg': im.convert('RGB').save(j['output'],format='JPEG',quality=88,optimize=True)\n else: im.save(j['output'],format='PNG',optimize=True)\n j['outputSize']=list(im.size)\njson.dump(jobs,open(sys.argv[2],'w'))`, path.join(temporary, 'jobs.json'), path.join(temporary, 'results.json')], { encoding: 'utf8' });
  if (python.status !== 0) throw new Error(python.stderr || 'Pillow resize failed');
  imageInfo.push(...JSON.parse(await fs.readFile(path.join(temporary, 'results.json'), 'utf8')));

  const output = {
    asset: { ...json.asset, generator: 'Mission Control Jr. static reference preparation', extras: { ...json.asset.extras, modification: `Textures limited to 1024px; static transforms baked; compatible geometry batched; unused UV sets and Sketchfab presentation floor removed; tangents recomputed. Source shape retained. Educational reference display; not the playable crewed rover.${filename === 'mars.glb' ? ' Globe legacy zero-specular diffuse material approximated with core metallic/roughness PBR while retaining its diffuse texture.' : ''}` } },
    scene: 0, scenes: [{ nodes: [0] }], nodes: [{ name: json.asset.extras?.title || outputName, mesh: 0 }],
    meshes: [{ name: outputName, primitives: [] }], materials: json.materials, textures: json.textures,
    samplers: json.samplers, images: [], accessors: [], bufferViews: [], buffers: [{ byteLength: 0 }],
    extensionsUsed: json.extensionsUsed?.length ? json.extensionsUsed : undefined,
  };
  const chunks = []; let offset = 0;
  const append = (bytes, target) => {
    const padding = (4 - offset % 4) % 4;
    if (padding) { chunks.push(Buffer.alloc(padding)); offset += padding; }
    const id = output.bufferViews.length;
    output.bufferViews.push({ buffer: 0, byteOffset: offset, byteLength: bytes.length, ...(target ? { target } : {}) });
    chunks.push(bytes); offset += bytes.length; return id;
  };
  const addAccessor = (attribute, isIndex = false) => {
    const array = isIndex ? Uint32Array.from(attribute.array) : Float32Array.from(attribute.array);
    const view = append(Buffer.from(array.buffer), isIndex ? 34963 : 34962);
    const a = { bufferView: view, componentType: isIndex ? 5125 : 5126, count: attribute.count, type: ['SCALAR', 'VEC2', 'VEC3', 'VEC4'][attribute.itemSize - 1] };
    if (attribute.itemSize === 3 && !isIndex) {
      a.min = [Infinity, Infinity, Infinity]; a.max = [-Infinity, -Infinity, -Infinity];
      for (let i = 0; i < array.length; i++) { a.min[i % 3] = Math.min(a.min[i % 3], array[i]); a.max[i % 3] = Math.max(a.max[i % 3], array[i]); }
    }
    output.accessors.push(a); return output.accessors.length - 1;
  };
  for (const group of groups.values()) {
    const geometry = group.geometries.length === 1 ? group.geometries[0] : mergeGeometries(group.geometries);
    if (!geometry) throw new Error('Static batching failed');
    const normalTexture = json.materials?.[group.material]?.normalTexture;
    const normalUV = geometry.attributes[normalTexture?.texCoord ? `uv${normalTexture.texCoord}` : 'uv'];
    if (normalTexture && geometry.attributes.normal && normalUV) {
      // A supplied Perseverance material uses TEXCOORD_1 for its normal map.
      // computeTangents reads the attribute called uv, so select that channel temporarily.
      const originalUV = geometry.attributes.uv;
      geometry.setAttribute('uv', normalUV);
      geometry.computeTangents();
      if (originalUV) geometry.setAttribute('uv', originalUV);
      else geometry.deleteAttribute('uv');
      const tangent = geometry.attributes.tangent;
      for (let i = 0; i < tangent.count; i++) {
        const direction = new THREE.Vector3().fromBufferAttribute(tangent, i);
        if (direction.lengthSq() < .5) {
          const normal = new THREE.Vector3().fromBufferAttribute(geometry.attributes.normal, i);
          direction.set(Math.abs(normal.y) < .9 ? 0 : 1, Math.abs(normal.y) < .9 ? 1 : 0, 0).cross(normal).normalize();
          tangent.setXYZW(i, direction.x, direction.y, direction.z, 1);
        }
      }
    }
    const attributes = {};
    for (const [semantic, name] of Object.entries(semantics)) if (geometry.attributes[name]) attributes[semantic] = addAccessor(geometry.attributes[name]);
    output.meshes[0].primitives.push({ attributes, indices: addAccessor(geometry.index, true), ...(group.material === undefined ? {} : { material: group.material }) });
  }
  for (let i = 0; i < imageInfo.length; i++) {
    const bytes = await fs.readFile(imageInfo[i].output);
    imageInfo[i].outputBytes = bytes.length;
    output.images.push({ ...json.images[i], bufferView: append(bytes) });
  }
  output.buffers[0].byteLength = offset;
  const jsonBytes = Buffer.from(JSON.stringify(output));
  const jsonPadding = (4 - jsonBytes.length % 4) % 4, binaryPadding = (4 - offset % 4) % 4;
  const jsonChunk = Buffer.concat([jsonBytes, Buffer.alloc(jsonPadding, 32)]), binaryChunk = Buffer.concat([...chunks, Buffer.alloc(binaryPadding)]);
  const header = Buffer.alloc(20); header.writeUInt32LE(0x46546c67); header.writeUInt32LE(2, 4); header.writeUInt32LE(28 + jsonChunk.length + binaryChunk.length, 8); header.writeUInt32LE(jsonChunk.length, 12); header.writeUInt32LE(0x4e4f534a, 16);
  const binaryHeader = Buffer.alloc(8); binaryHeader.writeUInt32LE(binaryChunk.length); binaryHeader.writeUInt32LE(0x004e4942, 4);
  const derivative = Buffer.concat([header, jsonChunk, binaryHeader, binaryChunk]);
  const validation = await validateBytes(new Uint8Array(derivative), { maxIssues: 1000 });
  if (validation.issues.numErrors) throw new Error(JSON.stringify(validation.issues));
  await fs.writeFile(path.join(destination, `${outputName}.glb`), derivative);
  const size = bounds.getSize(new THREE.Vector3()), center = bounds.getCenter(new THREE.Vector3());
  const item = {
    source: filename, derivative: `${outputName}.glb`, attribution: json.asset.extras,
    sourceBytes: original.length, derivativeBytes: derivative.length, externalResources: external,
    sourceDrawCalls: json.meshes.reduce((count, mesh) => count + mesh.primitives.length, 0), derivativeDrawCalls: groups.size,
    sourceMeshes: json.meshes.length, sourceNodes: json.nodes.length,
    sourceTriangles: json.meshes.reduce((total, mesh) => total + mesh.primitives.reduce((sum, primitive) => sum + json.accessors[primitive.indices ?? primitive.attributes.POSITION].count / 3, 0), 0),
    embeddedTextureCount: json.images?.length || 0,
    triangles: traversal.reduce((sum, item) => sum + item.triangles, 0), materials: json.materials?.length || 0,
    images: imageInfo.map(({ sourceSize, outputSize, outputBytes }) => ({ sourceSize, outputSize, outputBytes })),
    bounds: { min: bounds.min.toArray(), max: bounds.max.toArray(), size: size.toArray(), center: center.toArray() },
    fit: { scaleFor4MeterFootprint: 4 / Math.max(size.x, size.z), centerOnGroundOffset: [-center.x, -bounds.min.y, -center.z] },
    extensionsUsed: json.extensionsUsed || [], requiredExtensions: json.extensionsRequired || [],
    sourceExtensionsUsed: originalExtensionsUsed, sourceRequiredExtensions: originalExtensionsRequired,
    validation: { errors: validation.issues.numErrors, warnings: validation.issues.numWarnings, messages: validation.issues.messages },
  };
  report.push(item); console.log(JSON.stringify(item));
  await fs.rm(temporary, { recursive: true, force: true });
}
await fs.writeFile(path.join(destination, 'reference-assets-report.json'), JSON.stringify(report, null, 2));
